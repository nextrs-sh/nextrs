#!/usr/bin/env bash
# Builds the compatibility fixture against one Next.js version and runs every
# HTTP-level comparison against `next start`:
#
#   scripts/compat-suite.sh [--next VERSION] [--isolates N] [--out DIR] [--browser]
#                           [--cache-components] [--proxy] [--proxy-combinations]
#                           [--images] [--only-images]
#
# Without --next the fixture's pinned lockfile is used (npm ci, in place).
# With --next the fixture is copied to a temporary directory and that
# version is installed there, so the pinned baseline is never modified.
#
# Needs target/release/nextrs (cargo build --release -p nextrs-cli), Node.js
# and npm. --browser also runs the browser-driven Server Action suite
# (tests/browser: npm ci there, and a Chromium for playwright-core).
# --cache-components also builds fixtures/next-cache-components (Cache
# Components on) and runs tests/compat/cache-components.mjs against it.
# --proxy also builds fixtures/next-proxy (proxy.ts and next.config
# headers/redirects/rewrites) three times (default, basePath, trailingSlash)
# and runs tests/compat/proxy.mjs and tests/compat/routing-config.mjs on
# each (with --browser, tests/browser/proxy.mjs too). next start serves it
# on 0.0.0.0: bound to 127.0.0.1 it proxies its own proxy rewrites over
# HTTP (see tests/compat/proxy.mjs).
# --proxy-combinations (with --proxy) adds three builds of the same fixture:
# basePath with trailingSlash, a path assetPrefix and
# experimental.caseSensitiveRoutes (proxy, routing-config, and for the last
# two tests/compat/config-flags.mjs).
# --images builds fixtures/next-image four times (default; alt: basePath, SVG
# allowed, no localPatterns; asset-prefix: a path assetPrefix;
# asset-prefix-url: an absolute one), generating its images first, and runs
# tests/compat/image.mjs against the first two (with --browser,
# tests/browser/image.mjs too), tests/compat/image-https.mjs against the
# default build (HTTPS upstreams with a test CA made for the run) and
# tests/compat/image-asset-prefix.mjs against the assetPrefix builds. The suites start their own deterministic image upstream on a port
# fixed at build time (remotePatterns are compiled in).
# --only-images runs the --images part alone (no base fixture build or suites).
# Exits non-zero if any suite fails.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
next_version=""
isolates=1
out=""
browser=0
cache_components=0
proxy=0
combinations=0
images=0
only_images=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --next) next_version="$2"; shift 2 ;;
    --isolates) isolates="$2"; shift 2 ;;
    --out) out="$2"; shift 2 ;;
    --browser) browser=1; shift ;;
    --cache-components) cache_components=1; shift ;;
    --proxy) proxy=1; shift ;;
    --proxy-combinations) combinations=1; shift ;;
    --images) images=1; shift ;;
    --only-images) images=1; only_images=1; shift ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

work=""
pids=()
cleanup() {
  for pid in "${pids[@]}"; do kill -- "-$pid" 2>/dev/null || kill "$pid" 2>/dev/null || true; done
  wait 2>/dev/null || true
  if [[ -n "${work:-}" ]]; then rm -rf "$work"; fi
}
trap cleanup EXIT

nextrs="$root/target/release/nextrs"
[[ -x "$nextrs" ]] || { echo "build target/release/nextrs first" >&2; exit 2; }

if [[ -z "$next_version" ]]; then
  project="$root/fixtures/next-app"
  (cd "$project" && npm ci --no-audit --no-fund --loglevel=error)
else
  work="$(mktemp -d)"
  project="$work/next-app"
  mkdir -p "$project"
  # Tracked files only: next-env.d.ts and .next are generated by the build
  # and absent from a clean checkout.
  (cd "$root/fixtures/next-app" && cp -r app next.config.ts tsconfig.json package.json package-lock.json "$project/")
  (cd "$project" && npm install --no-audit --no-fund --loglevel=error --save-exact "next@$next_version")
fi
out="${out:-$(mktemp -d)}"
mkdir -p "$out"
# Absolute: the steps below run from other directories.
out="$(cd "$out" && pwd)"

# 5100-5499 holds none of the Fetch standard's "bad ports", which Node's
# fetch refuses (a random 4190, ManageSieve, failed every next start fetch).
# A base whose ports are all free (and none of them a system listener such
# as systemd-resolved's LLMNR on 5355, which accepts but never answers).
port_in_use() { (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null; }
for _ in $(seq 1 50); do
  base_port=$((5100 + RANDOM % 600))
  free=1
  for offset in $(seq 0 9); do
    if port_in_use $((base_port + offset)); then free=0; break; fi
  done
  [[ $free == 1 ]] && break
done
next_port=$base_port
nextrs_port=$((base_port + 1))
# The data-fetching fixtures' upstream API (tests/compat/upstream.mjs), and
# a port nothing listens on, both allowed by NextRS's network policy.
# The upstream also keeps the Server Action suites' mutation ledger.
upstream_port=$((base_port + 2))
closed_port=$((base_port + 3))
export NEXTRS_UPSTREAM="http://127.0.0.1:$upstream_port"

if [[ $only_images != 1 ]]; then
node "$root/tests/compat/upstream.mjs" --port "$upstream_port" > "$out/upstream.log" 2>&1 &
pids+=($!)

# The upstream runs during the build too: the ISR fixtures fetch from it
# when they are prerendered, as applications fetch their data at build time.
(cd "$project" && rm -rf .next && NEXT_TELEMETRY_DISABLED=1 npx next build > "$out/build.log" 2>&1) || {
  tail -40 "$out/build.log"; exit 1;
}
installed="$(node -p "require('$project/node_modules/next/package.json').version")"
echo "Next.js $installed built ($(cat "$project/.next/BUILD_ID"))"
fi


next_pid=""
nextrs_pid=""
start_servers() {
  # A server left over from a previous start would answer instead of the
  # one started now (and the new one would fail to bind): refuse.
  for port in "$next_port" "$nextrs_port"; do
    if curl -s --max-time 2 -o /dev/null "http://127.0.0.1:$port/"; then
      echo "port $port is still in use before starting the servers" >&2; exit 1
    fi
  done
  # next start runs as npx's child: give it its own process group (setsid
  # execs in place, so the group id is this pid) and signal the group.
  (cd "$project" && NEXT_TELEMETRY_DISABLED=1 exec setsid npx next start -H 127.0.0.1 -p "$next_port") >> "$out/next-start.log" 2>&1 &
  next_pid=$!
  pids+=($next_pid)
  # Short stall and request deadlines: the Server Action suite checks what
  # happens to a mutation when they fire. No other suite comes near them.
  "$nextrs" start "$project" --port "$nextrs_port" --js-runtime embedded-v8 --isolates "$isolates" \
    --js-stall-timeout 3 --request-timeout 15 \
    --js-env NEXTRS_UPSTREAM --net-allow "http://127.0.0.1:$upstream_port" \
    --net-allow "http://127.0.0.1:$closed_port" --net-allow-addr 127.0.0.1 \
    --cache-dir "$out/nextrs-cache" >> "$out/nextrs.log" 2>&1 &
  nextrs_pid=$!
  pids+=($nextrs_pid)
  for port in "$next_port" "$nextrs_port"; do
    for _ in $(seq 1 120); do
      curl -sf --max-time 2 -o /dev/null "http://127.0.0.1:$port/api/health" && break
      sleep 0.25
    done
    curl -sf --max-time 2 -o /dev/null "http://127.0.0.1:$port/api/health" || { echo "server on $port did not start" >&2; tail -20 "$out"/*.log; exit 1; }
  done
}
stop_servers() {
  kill -TERM -- "-$next_pid" 2>/dev/null || kill -TERM "$next_pid" 2>/dev/null || true
  kill -TERM "$nextrs_pid" 2>/dev/null || true
  # Wait for both ports to close; escalate, and fail rather than let a
  # later start talk to a server that is still running.
  for port in "$next_port" "$nextrs_port"; do
    for _ in $(seq 1 80); do
      curl -s --max-time 2 -o /dev/null "http://127.0.0.1:$port/" || break
      sleep 0.25
    done
  done
  if curl -s --max-time 2 -o /dev/null "http://127.0.0.1:$next_port/" || curl -s --max-time 2 -o /dev/null "http://127.0.0.1:$nextrs_port/"; then
    kill -KILL -- "-$next_pid" 2>/dev/null || true
    kill -KILL "$nextrs_pid" 2>/dev/null || true
    sleep 1
  fi
  for port in "$next_port" "$nextrs_port"; do
    if curl -s --max-time 2 -o /dev/null "http://127.0.0.1:$port/"; then
      echo "a server on port $port did not stop" >&2; exit 1
    fi
  done
  wait "$next_pid" "$nextrs_pid" 2>/dev/null || true
}
[[ $only_images != 1 ]] && start_servers

baseline="http://127.0.0.1:$next_port"
candidate="http://127.0.0.1:$nextrs_port"
status=0
run() {
  local name="$1"; shift
  if node "$@" > "$out/$name.txt" 2>&1; then
    echo "PASS  $name"
  else
    echo "FAIL  $name"; tail -25 "$out/$name.txt"; status=1
  fi
}
cd "$root"
if [[ $only_images != 1 ]]; then
run compare   tests/compat/compare.mjs   --baseline "$baseline" --candidate "$candidate" --project "$project" --json "$out/compare.json"
run semantic  tests/compat/semantic.mjs  --baseline "$baseline" --candidate "$candidate" --json "$out/semantic.json"
run streaming tests/compat/streaming.mjs --target "$candidate" --runs 20
run isolation tests/compat/isolation.mjs --target "$candidate" --requests 1200 --concurrency 64 --aborts 20 --json "$out/isolation.json"
run features  tests/compat/features.mjs  --target "$candidate" --requests 600 --concurrency 64 --json "$out/features.json"
run data      tests/compat/data.mjs      --baseline "$baseline" --candidate "$candidate" --upstream "$NEXTRS_UPSTREAM" --closed-port "$closed_port" --json "$out/data.json"
run actions   tests/compat/actions.mjs   --baseline "$baseline" --candidate "$candidate" --upstream "$NEXTRS_UPSTREAM" \
  --project "$project" --stall-ms 3000 --request-timeout-ms 15000 --json "$out/actions.json"
run isr       tests/compat/isr.mjs       --baseline "$baseline" --candidate "$candidate" --upstream "$NEXTRS_UPSTREAM" \
  --project "$project" --isolates "$isolates" --json "$out/isr.json"
if [[ $browser == 1 ]]; then
  run browser tests/browser/actions.mjs --baseline "$baseline" --candidate "$candidate" --upstream "$NEXTRS_UPSTREAM" --json "$out/browser.json"
fi
# The same feature checks against next start: the reference must pass too.
run features-next-start tests/compat/features.mjs --target "$baseline" --requests 600 --concurrency 64 --json "$out/features-next-start.json"

# Data cache persistence: prepare, restart both servers, verify.
restart_ns="restart-$RANDOM"
node tests/compat/restart.mjs --phase prepare --ns "$restart_ns" --baseline "$baseline" --candidate "$candidate" \
  --upstream "$NEXTRS_UPSTREAM" --json "$out/restart-prepare.json" > "$out/restart.txt" 2>&1
sleep 1
stop_servers
start_servers
run restart   tests/compat/restart.mjs   --phase verify --ns "$restart_ns" --baseline "$baseline" --candidate "$candidate" --upstream "$NEXTRS_UPSTREAM" --prepared "$out/restart-prepare.json" --json "$out/restart.json"
fi

if [[ $cache_components == 1 ]]; then
  stop_servers
  if [[ -z "$next_version" ]]; then
    project="$root/fixtures/next-cache-components"
    (cd "$project" && npm ci --no-audit --no-fund --loglevel=error)
  else
    project="$work/next-cache-components"
    mkdir -p "$project"
    (cd "$root/fixtures/next-cache-components" && cp -r app next.config.ts tsconfig.json package.json package-lock.json "$project/")
    (cd "$project" && npm install --no-audit --no-fund --loglevel=error --save-exact "next@$next_version")
  fi
  (cd "$project" && rm -rf .next && NEXT_TELEMETRY_DISABLED=1 npx next build > "$out/build-cache-components.log" 2>&1) || {
    tail -40 "$out/build-cache-components.log"; exit 1;
  }
  start_servers
  run cache-components tests/compat/cache-components.mjs --baseline "$baseline" --candidate "$candidate" \
    --upstream "$NEXTRS_UPSTREAM" --project "$project" --isolates "$isolates" --json "$out/cache-components.json"
  cc_ns="cc-$RANDOM"
  node tests/compat/cache-components.mjs --phase prepare --ns "$cc_ns" --baseline "$baseline" --candidate "$candidate" \
    --upstream "$NEXTRS_UPSTREAM" --project "$project" --json "$out/cc-restart-prepare.json" > "$out/cc-restart.txt" 2>&1
  stop_servers
  start_servers
  node tests/compat/cache-components.mjs --phase verify --ns "$cc_ns" --baseline "$baseline" --candidate "$candidate" \
    --upstream "$NEXTRS_UPSTREAM" --project "$project" --prepared "$out/cc-restart-prepare.json" --json "$out/cc-restart.json" >> "$out/cc-restart.txt" 2>&1
  tail -1 "$out/cc-restart.txt"
fi

if [[ $proxy == 1 ]]; then
  stop_servers
  if [[ -z "$next_version" ]]; then
    project="$root/fixtures/next-proxy"
    (cd "$project" && npm ci --no-audit --no-fund --loglevel=error)
  else
    project="$work/next-proxy"
    mkdir -p "$project"
    (cd "$root/fixtures/next-proxy" && cp -r app public proxy.ts next.config.ts tsconfig.json package.json package-lock.json "$project/")
    (cd "$project" && npm install --no-audit --no-fund --loglevel=error --save-exact "next@$next_version")
  fi
  export NEXTRS_CLOSED_PORT="$closed_port"
  variants=(default base-path trailing-slash)
  [[ $combinations == 1 ]] && variants+=(base-path-trailing-slash asset-prefix case-sensitive)
  for variant in "${variants[@]}"; do
    dist=".next"; [[ $variant != default ]] && dist=".next-$variant"
    prefix=""; [[ $variant == base-path* ]] && prefix="/base"
    (cd "$project" && rm -rf "$dist" && NEXTRS_VARIANT="$variant" NEXT_TELEMETRY_DISABLED=1 npx next build > "$out/build-proxy-$variant.log" 2>&1) || {
      tail -40 "$out/build-proxy-$variant.log"; exit 1;
    }
    for port in "$next_port" "$nextrs_port"; do
      if curl -s --max-time 2 -o /dev/null "http://127.0.0.1:$port/"; then echo "port $port is still in use" >&2; exit 1; fi
    done
    (cd "$project" && NEXTRS_VARIANT="$variant" NEXT_TELEMETRY_DISABLED=1 exec setsid npx next start -H 0.0.0.0 -p "$next_port") >> "$out/next-start-proxy.log" 2>&1 &
    next_pid=$!
    pids+=($next_pid)
    "$nextrs" start "$project/$dist" --port "$nextrs_port" --js-runtime embedded-v8 --isolates "$isolates" \
      --js-stall-timeout 3 --request-timeout 15 \
      --js-env NEXTRS_UPSTREAM --js-env NEXTRS_CLOSED_PORT --net-allow "http://127.0.0.1:$upstream_port" \
      --net-allow-addr 127.0.0.1 >> "$out/nextrs-proxy.log" 2>&1 &
    nextrs_pid=$!
    pids+=($nextrs_pid)
    for port in "$next_port" "$nextrs_port"; do
      for _ in $(seq 1 120); do
        curl -s --max-time 2 -o /dev/null "http://127.0.0.1:$port$prefix/api/health" && break
        sleep 0.25
      done
    done
    extra=()
    [[ $variant == default ]] && extra=(--request-timeout-ms 15000 --stall-ms 3000)
    run "proxy-$variant" tests/compat/proxy.mjs --baseline "$baseline" --candidate "$candidate" --upstream "$NEXTRS_UPSTREAM" \
      --dist "$project/$dist" --variant "$variant" "${extra[@]}" --json "$out/proxy-$variant.json"
    run "routing-config-$variant" tests/compat/routing-config.mjs --baseline "$baseline" --candidate "$candidate" \
      --variant "$variant" --json "$out/routing-config-$variant.json"
    if [[ $variant == asset-prefix || $variant == case-sensitive ]]; then
      run "config-flags-$variant" tests/compat/config-flags.mjs --baseline "$baseline" --candidate "$candidate" \
        --variant "$variant" --json "$out/config-flags-$variant.json"
    fi
    if [[ $browser == 1 && ( $variant == default || $variant == base-path ) ]]; then
      run "browser-proxy-$variant" tests/browser/proxy.mjs --baseline "$baseline" --candidate "$candidate" \
        --base-path "$prefix" --json "$out/browser-proxy-$variant.json"
    fi
    stop_servers
  done
fi

if [[ $images == 1 ]]; then
  stop_servers
  if [[ -z "$next_version" ]]; then
    project="$root/fixtures/next-image"
    (cd "$project" && npm ci --no-audit --no-fund --loglevel=error)
  else
    project="$work/next-image"
    mkdir -p "$project"
    (cd "$root/fixtures/next-image" && cp -r app scripts next.config.ts tsconfig.json package.json package-lock.json "$project/")
    (cd "$project" && npm install --no-audit --no-fund --loglevel=error --save-exact "next@$next_version")
  fi
  [[ $only_images == 1 ]] && installed="$(node -p "require('$project/node_modules/next/package.json').version")"
  image_port=$((base_port + 4))
  # HTTPS upstreams on +5 (test CA) and +6 (untrusted CA); a CDN stand-in
  # for the absolute assetPrefix build on +7. Certificates are made for this
  # run; next start trusts the test CA through NODE_EXTRA_CA_CERTS, NextRS
  # through --net-ca-file.
  https_port=$((base_port + 5))
  cdn_port=$((base_port + 7))
  export NEXTRS_IMAGE_UPSTREAM_PORT="$image_port" NEXTRS_IMAGE_HTTPS_PORT="$https_port" NEXTRS_IMAGE_CDN_PORT="$cdn_port"
  certs="$out/certs"
  "$root/tests/compat/image-certs.sh" "$certs" > /dev/null
  (cd "$project" && node scripts/make-images.mjs > "$out/make-images.log" 2>&1) || { tail -20 "$out/make-images.log"; exit 1; }
  for variant in default alt asset-prefix asset-prefix-url; do
    dist=".next"; [[ $variant != default ]] && dist=".next-$variant"
    prefix=""; [[ $variant == alt ]] && prefix="/base"
    (cd "$project" && rm -rf "$dist" && NEXTRS_VARIANT="$variant" NEXT_TELEMETRY_DISABLED=1 npx next build > "$out/build-image-$variant.log" 2>&1) || {
      tail -40 "$out/build-image-$variant.log"; exit 1;
    }
    for port in "$next_port" "$nextrs_port"; do
      if curl -s --max-time 2 -o /dev/null "http://127.0.0.1:$port/"; then echo "port $port is still in use" >&2; exit 1; fi
    done
    (cd "$project" && NEXTRS_VARIANT="$variant" NEXT_TELEMETRY_DISABLED=1 NODE_EXTRA_CA_CERTS="$certs/test-ca.pem" \
      exec setsid npx next start -H 127.0.0.1 -p "$next_port") >> "$out/next-start-image.log" 2>&1 &
    next_pid=$!
    pids+=($next_pid)
    "$nextrs" start "$project/$dist" --port "$nextrs_port" --js-runtime embedded-v8 --isolates "$isolates" \
      --net-allow "http://127.0.0.1:$image_port" --net-allow "https://localhost:$https_port" \
      --net-allow "https://127.0.0.1:$https_port" --net-allow "https://localhost:$((https_port + 1))" \
      --net-allow "http://127.0.0.1:$cdn_port" --net-allow-addr 127.0.0.1 --net-allow-addr ::1 --net-ca-file "$certs/test-ca.pem" \
      >> "$out/nextrs-image.log" 2>&1 &
    nextrs_pid=$!
    pids+=($nextrs_pid)
    for port in "$next_port" "$nextrs_port"; do
      for _ in $(seq 1 120); do
        curl -s --max-time 2 -o /dev/null "http://127.0.0.1:$port$prefix/second" && break
        sleep 0.25
      done
    done
    if [[ $variant == asset-prefix* ]]; then
      run "image-$variant" tests/compat/image-asset-prefix.mjs --baseline "$baseline" --candidate "$candidate" --project "$project" \
        --variant "$variant" --upstream-port "$image_port" --cdn-port "$cdn_port" --json "$out/image-$variant.json"
      stop_servers
      continue
    fi
    run "image-$variant" tests/compat/image.mjs --baseline "$baseline" --candidate "$candidate" --project "$project" \
      --variant "$variant" --upstream-port "$image_port" --json "$out/image-$variant.json"
    if [[ $variant == default ]]; then
      run "image-https" tests/compat/image-https.mjs --baseline "$baseline" --candidate "$candidate" --project "$project" \
        --certs "$certs" --upstream-port "$image_port" --https-port "$https_port" --json "$out/image-https.json"
    fi
    if [[ $browser == 1 ]]; then
      run "browser-image-$variant" tests/browser/image.mjs --baseline "$baseline" --candidate "$candidate" \
        --photos "$project/public/photos" --base-path "$prefix" --upstream-port "$image_port" --json "$out/browser-image-$variant.json"
    fi
    stop_servers
  done
fi

summary="$(node -e "const r=require('$out/compare.json');const c={};for(const x of r.results??r)c[x.verdict]=(c[x.verdict]??0)+1;console.log(JSON.stringify(c))" 2>/dev/null || echo '{}')"
echo "compare: $summary"
echo "{\"next\":\"$installed\",\"isolates\":$isolates,\"status\":$status,\"compare\":$summary}" > "$out/summary.json"
exit $status
